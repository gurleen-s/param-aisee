def save_meeting_transcript():
    """Save the extracted meeting transcript"""
    meeting_data = extract_transcripts_from_logs()
    
    filename = f"doctor_meeting_{datetime.now().strftime('%Y%m%d_%H%M%S')}.json"
    filepath = f"backend/recordings/{filename}"
    
    with open(filepath, 'w') as f:
        json.dump(meeting_data, f, indent=2)
    
    print(f"✅ Saved {meeting_data['transcript_count']} transcripts to {filepath}")
    print(f"📊 Meeting: {meeting_data['meeting_name']}")
    print(f"🕒 Created: {meeting_data['created_at']}")
    
    # Also create a readable text version
    text_filename = f"doctor_meeting_{datetime.now().strftime('%Y%m%d_%H%M%S')}.txt"
    text_filepath = f"backend/recordings/{text_filename}"
    
    with open(text_filepath, 'w') as f:
        f.write(f"Doctor Meeting Transcript\n")
        f.write(f"Created: {meeting_data['created_at']}\n")
        f.write(f"Total Entries: {meeting_data['transcript_count']}\n")
        f.write(f"{'='*50}\n\n")
        
        for transcript in meeting_data["transcripts"]:
            f.write(f"[{transcript['timestamp']}] {transcript['content']}\n")
    
    print(f"📄 Text version saved to {text_filepath}")
    
    return filepath, meeting_data

